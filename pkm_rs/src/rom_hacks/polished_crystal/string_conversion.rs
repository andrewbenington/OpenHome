pub fn get_gb_char_from_byte(byte: &u8) -> char {
  let map: HashMap<u8, char> = GAMEBOY_BYTE_CHAR_MAPPING.clone();
  if map.contains_key(byte) {
    map[byte]
  } else {
    '\0'
  }
}
