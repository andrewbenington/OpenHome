export const SWSH_TR_BYTE_COUNT = 14
export const moveFromSwShTrFlag = (i: number) => Moves[MoveTrIndexLookup[i]]

export function movesFromSwshTrFlags(trFlags: Uint8Array): Move[] {
  return getFlagsInArrayRange(trFlags, 0, SWSH_TR_BYTE_COUNT).map(moveFromSwShTrFlag)
}

export function trIndexForMove(moveIndex: number): Option<number> {
  if (moveIndex >= InvertedLookup.length) return undefined
  const trIndex = InvertedLookup[moveIndex]
  return trIndex === -1 ? undefined : trIndex
}
